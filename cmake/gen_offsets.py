#!/usr/bin/env python3
"""Generate eft_offsets.hpp from eft.offsets.json.

Usage: gen_offsets.py <input.json> <output.hpp>

The header only gets rewritten when its content changes, so unrelated edits don't trigger
rebuilds. Any schema error aborts the build with a message pointing at the offending entry.
"""
import json
import re
import sys

SCHEMA = 1
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
RESERVED_GROUPS = {"build", "bootstrap", "unity_rva", "unity", "managed"}


class SchemaError(Exception):
    pass


def parse_value(raw, where, bits):
    if isinstance(raw, bool):
        raise SchemaError(f"{where}: boolean is not a valid offset")
    if isinstance(raw, int):
        value = raw
    elif isinstance(raw, str) and re.fullmatch(r"0[xX][0-9A-Fa-f]+", raw):
        value = int(raw, 16)
    elif isinstance(raw, str) and re.fullmatch(r"[1-9][0-9]*|0", raw):
        value = int(raw, 10)
    else:
        raise SchemaError(f"{where}: expected an integer or '0x…' hex string, got {raw!r}")
    if not 0 <= value < (1 << bits):
        raise SchemaError(f"{where}: value {raw!r} does not fit in {bits} bits")
    return value


def ident(name, where):
    if not isinstance(name, str) or not IDENT.match(name):
        raise SchemaError(f"{where}: {name!r} is not a valid C++ identifier")
    return name


def cstr(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def comment(text):
    # Values end up in // line comments: a newline would let text escape into code.
    return text.replace("*/", "* /").replace("\r", " ").replace("\n", " ")


def hexs(value):
    return f"0x{value:X}"


def emit_dotted(lines, ns, table, where, bits, ctype):
    """Emit a {"Type.Member": value} table as namespace ns::Type::Member."""
    groups = {}
    for key, raw in table.items():
        parts = key.split(".")
        if len(parts) != 2:
            raise SchemaError(f"{where}: key {key!r} must look like 'Type.Member'")
        t = ident(parts[0], f"{where}.{key}")
        m = ident(parts[1], f"{where}.{key}")
        groups.setdefault(t, []).append((m, parse_value(raw, f"{where}.{key}", bits)))
    lines.append(f"namespace {ns} {{")
    for t in sorted(groups):
        lines.append(f"    namespace {t} {{")
        for m, v in groups[t]:
            lines.append(f"        inline constexpr {ctype} {m} = {hexs(v)};")
        lines.append("    }")
    lines.append(f"}} // namespace {ns}")
    lines.append("")


def generate(doc):
    if doc.get("schema") != SCHEMA:
        raise SchemaError(f"schema must be {SCHEMA}, got {doc.get('schema')!r}")

    lines = [
        "// GENERATED by cmake/gen_offsets.py from game/eft/offsets/eft.offsets.json.",
        "// Do not edit. Edit the JSON (or regenerate it with tools/update-offsets.py).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <optional>",
        "#include <string_view>",
        "",
        "namespace off {",
        "",
    ]

    # ---- build fingerprints --------------------------------------------------------------
    lines += [
        "namespace build {",
        "    struct ModuleFingerprint {",
        "        std::string_view module;",
        "        bool known;                 // false: no fingerprint recorded for this module",
        "        std::uint32_t peTimestamp;  // IMAGE_FILE_HEADER.TimeDateStamp",
        "        std::uint32_t imageSize;    // IMAGE_OPTIONAL_HEADER64.SizeOfImage",
        "    };",
        "    inline constexpr ModuleFingerprint kModules[] = {",
    ]
    build = doc.get("build", {})
    if not isinstance(build, dict) or not build:
        raise SchemaError("build: must be a non-empty object of module -> fingerprint|null")
    for module, fp in build.items():
        if fp is None:
            lines.append(f'        {{"{cstr(module)}", false, 0, 0}},')
        elif not isinstance(fp, dict):
            raise SchemaError(f"build.{module}: expected null or {{peTimestamp, imageSize}}")
        else:
            ts = parse_value(fp.get("peTimestamp"), f"build.{module}.peTimestamp", 32)
            size = parse_value(fp.get("imageSize"), f"build.{module}.imageSize", 32)
            lines.append(f'        {{"{cstr(module)}", true, {hexs(ts)}, {hexs(size)}}},')
    lines += ["    };", "} // namespace build", ""]

    # ---- flat tables -----------------------------------------------------------------------
    for ns, key in (("bootstrap", "bootstrap"), ("unity_rva", "unityRvas")):
        lines.append(f"namespace {ns} {{")
        for name, raw in doc.get(key, {}).items():
            v = parse_value(raw, f"{key}.{name}", 64)
            lines.append(f"    inline constexpr std::uint64_t {ident(name, f'{key}.{name}')} = {hexs(v)};")
        lines += [f"}} // namespace {ns}", ""]

    emit_dotted(lines, "unity", doc.get("unityLayout", {}), "unityLayout", 32, "std::uint32_t")
    emit_dotted(lines, "managed", doc.get("managedLayout", {}), "managedLayout", 32, "std::uint32_t")

    # ---- catalogue: types, fields, literals, grouped by group --------------------------------
    groups = {}
    seen = set()

    def add(group, name, decl, where):
        group = ident(group, f"{where}.group")
        name = ident(name, f"{where}.name")
        if group in RESERVED_GROUPS:
            raise SchemaError(f"{where}: group name {group!r} is reserved")
        if (group, name) in seen:
            raise SchemaError(f"{where}: duplicate entry {group}::{name}")
        seen.add((group, name))
        groups.setdefault(group, []).append(decl(name))

    for i, e in enumerate(doc.get("types", [])):
        where = f"types[{i}] ({e.get('group')}::{e.get('name')})"
        v = parse_value(e.get("value"), where, 31)
        cls = comment(e.get("class", "?"))
        add(e.get("group"), e.get("name"),
            lambda n, v=v, cls=cls: f"    inline constexpr std::int32_t {n} = {hexs(v)}; // type index of {cls}",
            where)

    for i, e in enumerate(doc.get("fields", [])):
        where = f"fields[{i}] ({e.get('group')}::{e.get('name')})"
        optional = e.get("optional") is True
        # Optional fields (not yet known for every build) may have a null value; code checks them.
        v = None if optional and e.get("value") is None else parse_value(e.get("value"), where, 32)
        note = f"{e.get('class', '?')} :: {e.get('field', '?')}"
        if e.get("static"):
            note += " [static]"
        if optional:
            note += " [optional]"
        note = comment(note)
        if optional:
            init = "std::nullopt" if v is None else hexs(v)
            decl = lambda n, init=init, note=note: (
                f"    inline constexpr std::optional<std::uint32_t> {n} = {init}; // {note}")
        else:
            decl = lambda n, v=v, note=note: f"    inline constexpr std::uint32_t {n} = {hexs(v)}; // {note}"
        add(e.get("group"), e.get("name"), decl, where)

    for i, e in enumerate(doc.get("literals", [])):
        where = f"literals[{i}] ({e.get('group')}::{e.get('name')})"
        v = parse_value(e.get("value"), where, 32)
        note = comment(e.get("note", "uncatalogued literal"))
        add(e.get("group"), e.get("name"),
            lambda n, v=v, note=note: f"    inline constexpr std::uint32_t {n} = {hexs(v)}; // {note}",
            where)

    for group in sorted(groups):
        lines.append(f"namespace {group} {{")
        lines += groups[group]
        lines += [f"}} // namespace {group}", ""]

    lines += ["} // namespace off", ""]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    try:
        with open(src, encoding="utf-8") as f:
            doc = json.load(f)
        text = generate(doc)
    except (OSError, json.JSONDecodeError, SchemaError) as exc:
        print(f"gen_offsets.py: {src}: {exc}", file=sys.stderr)
        return 1
    try:
        with open(dst, encoding="utf-8") as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    import os
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
