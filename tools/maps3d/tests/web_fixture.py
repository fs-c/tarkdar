"""Writes web/src/map3d/chunk.fixture.ts: a small dataset chunk as this pipeline writes it and
the arrays this pipeline reads back from it, for the viewer's decoder test (dataset.test.ts).

    .venv/bin/python -m tests.web_fixture        (in tools/maps3d; after a change of the format)
"""

from __future__ import annotations

import base64
import json
import tempfile
from pathlib import Path

import numpy as np

from . import support  # noqa: F401
from t3d import dataset, ground

TARGET = Path(__file__).resolve().parents[3] / "web" / "src" / "map3d" / "chunk.fixture.ts"


def fixture_dataset() -> dataset.Dataset:
    # A flat shaded "cell" (a square pyramid without a base) and a smooth strip of "terrain".
    cell = dataset.Geom(
        "cell_0_0_structure", "mesh",
        np.array([[100, 0, -40], [130.5, 0, -40], [130.5, 0, -9.25], [100, 0, -9.25], [115, 21.75, -25]], dtype=np.float32),
        np.zeros((5, 3), dtype=np.float32),
        np.array([0, 1, 4, 1, 2, 4, 2, 3, 4, 3, 0, 4], dtype=np.uint32),
        np.array([[0, 12]], dtype=np.uint32),
        np.array([[200, 10, 10, 255], [10, 200, 10, 255], [10, 10, 200, 255], [90, 90, 90, 255], [255, 255, 255, 255]],
                 dtype=np.uint8),
        flat=True)
    slope = np.array([[0, 0, 0], [8, 1, 0], [16, 4, 0], [0, 0, -8], [8, 1, -8], [16, 4, -8]], dtype=np.float32)
    normal = np.array([[-0.2, 0.9, 0.1]] * 6, dtype=np.float32)
    terrain = dataset.Geom(
        "Terrain_slice", "terrain", slope, normal / np.linalg.norm(normal, axis=1, keepdims=True),
        np.array([0, 1, 3, 1, 4, 3, 1, 2, 4, 2, 5, 4], dtype=np.uint32), np.array([[0, 12]], dtype=np.uint32),
        np.full((6, 4), 255, dtype=np.uint8))
    move = np.eye(4)
    move[:3, 3] = [-5, 2, 7]
    ds = dataset.Dataset(
        name="fixture", label="Fixture", tag="FIXTURE", profile="overview", scenes=[{"level": "cell 0,0", "path": "cells/cell_0_0"}],
        geoms=[cell, terrain],
        instances=[dataset.Instance(0, np.eye(4), 0, [dataset.Slot("structure")]),
                   dataset.Instance(1, move, 0, [dataset.Slot("terrain")])])
    ds.ground = ground.GroundMap((-8.0, 4.0), 1.0, np.array([[-3.3, 0.0, 12.5], [70.0, 69.98, -3.3]], dtype=np.float32),
                                 np.array([[0, 1, 0], [0, 0, 1]], dtype=bool))
    return ds


def render() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        index = dataset.write(fixture_dataset(), tmp)
        chunk = (Path(tmp) / index["chunks"][0]["file"]).read_bytes()
        _, [(meta, a)] = dataset.read(tmp)
    expected = {name: a[name].reshape(-1).tolist()
                for name in ("positions", "normals", "colors", "indices16", "ground_height", "ground_building",
                             "mesh_vertex_count", "mesh_flags")}
    expected["positions"] = [float(np.float32(v)) for v in expected["positions"]]
    return (
        "// Generated by tools/maps3d/tests/web_fixture.py (see there): a chunk as the pipeline writes it and\n"
        "// what the pipeline reads back from it. Do not edit.\n\n"
        f"export const CHUNK_BASE64 =\n  \"{base64.b64encode(chunk).decode()}\";\n\n"
        f"export const CHUNK_GROUND = {json.dumps(meta['ground'])};\n\n"
        "export const CHUNK_ARRAYS: Record<string, number[]> = {\n"
        + "".join(f"  {name}: {json.dumps(values)},\n" for name, values in expected.items())
        + "};\n")


if __name__ == "__main__":
    TARGET.write_text(render())
    print(f"wrote {TARGET}")
